const LOCAL_STORAGE_KEY = 'technokraft_calls_records_v1';

export function getStoredCalls(): CallRecord[] {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (err) {
    console.error('Failed reading calls from localStorage', err);
  }
  return INITIAL_CALL_RECORDS;
}

export function saveStoredCalls(calls: CallRecord[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(calls));
  } catch (err) {
    console.error('Failed writing calls to localStorage', err);
  }
}
