const generateMonthlyAttendance = (
  present = 18,
  absent = 1,
  leave = 2,
  late = 3,
  avgHours = '7h 52m',
  totalHours = '141h',
  overtime = '6h'
) => {
  const days: {
    dayNumber: number;
    dayLabel: string;
    date: string;
    status: 'Present' | 'Absent' | 'Half Day' | 'Leave' | 'Late' | 'Holiday';
    loginTime?: string;
    logoutTime?: string;
    workingHours?: string;
    notes?: string;
  }[] = [];

  const dayLabels = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

  for (let i = 1; i <= 21; i++) {
    const dayLabel = dayLabels[(i - 1) % 7];
    const isWeekend = dayLabel === 'Sat' || dayLabel === 'Sun';

    let status: 'Present' | 'Absent' | 'Half Day' | 'Leave' | 'Late' | 'Holiday' = 'Present';
    let login = '09:15 AM';
    let logout = '06:15 PM';
    let hours = '8h 15m';

    if (isWeekend) {
      status = 'Holiday';
      login = '—';
      logout = '—';
      hours = '—';
    } else if (i === 3) {
      status = 'Late';
      login = '09:48 AM';
      hours = '7h 35m';
    } else if (i === 5) {
      status = 'Leave';
      login = '—';
      logout = '—';
      hours = '0h';
    } else if (i === 12) {
      status = 'Half Day';
      login = '09:10 AM';
      logout = '01:30 PM';
      hours = '4h 20m';
    } else if (i === 16 && absent > 0) {
      status = 'Absent';
      login = '—';
      logout = '—';
      hours = '0h';
    }

    days.push({
      dayNumber: i,
      dayLabel,
      date: `2026-09-${i < 10 ? '0' + i : i}`,
      status,
      loginTime: login,
      logoutTime: logout,
      workingHours: hours,
    });
  }

  return {
    presentDays: present,
    absentDays: absent,
    leaveDays: leave,
    lateDays: late,
    workingDays: 21,
    averageWorkingHours: avgHours,
    totalWorkingHours: totalHours,
    expectedDailyHours: '8h/day',
    overtimeHours: overtime,
    dailyRecords: days,
  };
};

