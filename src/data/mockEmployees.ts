// Generate Today's Attendance Table Records from the Employee List
export const getTodayAttendanceRecords = (
  employees: Employee[]
): DailyAttendanceRecord[] => {
  return employees.map((emp) => {
    let logoutTime = emp.logoutTime || '—';
    let workingMinutes = 0;
    let breakTime = '45m';
    let breakMinutes = 45;
    let session = emp.todayWorkingTime;

    if (emp.todayAttendanceStatus === 'Present' || emp.todayAttendanceStatus === 'Late') {
      workingMinutes = 480;
      if (emp.workStatus === 'Working') {
        logoutTime = 'Active (Working)';
      } else if (!emp.logoutTime) {
        logoutTime = '06:12 PM';
      }
    } else if (emp.todayAttendanceStatus === 'Half Day') {
      workingMinutes = 240;
      breakTime = '20m';
      breakMinutes = 20;
    } else {
      breakTime = '0m';
      breakMinutes = 0;
      session = '0h 00m';
    }

    return {
      id: `att-${emp.id}`,
      employeeId: emp.id,
      employeeCode: emp.employeeCode,
      employeeName: emp.name,
      employeeRole: emp.role,
      department: emp.department,
      avatar: emp.avatar,
      date: '07 Sep 2026',
      loginTime: emp.loginTime,
      logoutTime,
      workingHours: emp.todayWorkingTime,
      workingMinutes,
      breakTime,
      breakMinutes,
      sessionDuration: session,
      status: emp.todayAttendanceStatus,
      currentActivity: emp.currentActivity,
      workStatus: emp.workStatus,
    };
  });
};
